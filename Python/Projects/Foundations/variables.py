age = 25
# 'age' is variable name, '=' is assignment, 25 is integer value
print("Age:", age)
print("Type:", type(age))   # type() shows the data type

# ---- Data Type 2: Float (decimal number) ----
price = 99.99
print("Price:", price)
print("Type:", type(price))

# ---- Data Type 3: String (text) ----
name = "Rahul"
print("Name:", name)
print("Type:", type(name))

# ---- Data Type 4: Boolean (True/False) ----
is_student = True
print("Is Student:", is_student)
print("Type:", type(is_student))

# ---- Multiple Assignment ----
x, y, z = 10, 20, 30
print("x =", x, "y =", y, "z =", z)